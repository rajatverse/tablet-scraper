import requests, re, os
from dotenv import load_dotenv

load_dotenv(os.path.join(os.path.dirname(os.path.dirname(__file__)), "..", ".env"))
WP_SITE_URL = os.getenv("WP_SITE_URL", "https://toptablets.in").rstrip("/")
WP_USERNAME = os.getenv("WP_USERNAME")
WP_APP_PASSWORD = os.getenv("WP_APP_PASSWORD")

session = requests.Session()
r_login = session.post(f"{WP_SITE_URL}/wp-login.php", data={
    "log": WP_USERNAME, "pwd": WP_APP_PASSWORD, "rememberme": "forever", "wp-submit": "Log In"
}, headers={"User-Agent": "Mozilla/5.0"})

print("Login status:", r_login.status_code, "Cookies:", len(session.cookies))
r_admin = session.get(f"{WP_SITE_URL}/wp-admin/index.php")
print("Admin access:", r_admin.status_code)

nonces = re.findall(r'wpApiSettings\s*=\s*\{\s*"root":[^}]*"nonce":"([^"]+)"', r_admin.text)
print("REST Nonce:", nonces)

if nonces:
    nonce = nonces[0]
    me = session.get(f"{WP_SITE_URL}/wp-json/wp/v2/users/me", headers={"X-WP-Nonce": nonce})
    print("Users/me:", me.status_code, me.json().get("name"))

    post_payload = {
        "title": "[Pipeline Test] TopTablets Automation Draft",
        "status": "draft",
        "content": "<p>This is a test draft generated by the automated pipeline.</p>",
        "categories": [1],
    }
    res = session.post(f"{WP_SITE_URL}/wp-json/wp/v2/posts", headers={"X-WP-Nonce": nonce}, json=post_payload)
    print("Post Creation Status:", res.status_code)
    if res.status_code in [200, 201]:
        data = res.json()
        print("Created Post ID:", data.get("id"), "| Link:", data.get("link"))
        # Clean up test post by trashing it
        del_res = session.delete(f"{WP_SITE_URL}/wp-json/wp/v2/posts/{data.get('id')}", headers={"X-WP-Nonce": nonce})
        print("Trashed test post:", del_res.status_code)
    else:
        print("Error:", res.text[:300])
